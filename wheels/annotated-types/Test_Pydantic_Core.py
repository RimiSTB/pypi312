def test_model_dump():
    from pydantic import BaseModel

    class Data(BaseModel):
        x: int
        y: int

    d = Data(x=1, y=2)
    dumped = d.model_dump()
    check(isinstance(dumped, dict), "not dict")
    check(dumped["x"] == 1, "x mismatch")
    check(dumped["y"] == 2, "y mismatch")
    print("  model_dump:", dumped)


def test_model_validate():
    from pydantic import BaseModel

    class Data(BaseModel):
        x: int
        y: int

    d = Data.model_validate({"x": 10, "y": 20})
    check(d.x == 10, "x mismatch")
    check(d.y == 20, "y mismatch")
    print("  model_validate:", d.model_dump())


