def test_discriminated_union():
    from pydantic import BaseModel
    from typing import Literal

    class Cat(BaseModel):
        type: Literal["cat"] = "cat"
        meow_volume: int

    class Dog(BaseModel):
        type: Literal["dog"] = "dog"
        bark_volume: int

    class Pet(BaseModel):
        pet: Cat | Dog

    p_cat = Pet(pet=Cat(meow_volume=5))
    check(p_cat.pet.type == "cat", "type")
    print("  discriminated union: OK")


