def test_simple_model():
    from pydantic import BaseModel

    class User(BaseModel):
        name: str
        age: int

    u = User(name="Alice", age=30)
    check(u.name == "Alice", "name mismatch")
    check(u.age == 30, "age mismatch")
    print("  simple model:", u.model_dump())


def test_model_validation_error():
    from pydantic import BaseModel, ValidationError

    class User(BaseModel):
        name: str
        age: int

    try:
        User(name="Alice", age="not_a_number")
        check(False, "should have raised")
    except ValidationError as e:
        check(len(e.errors()) > 0, "no errors")
        print("  validation error caught:", len(e.errors()), "errors")


