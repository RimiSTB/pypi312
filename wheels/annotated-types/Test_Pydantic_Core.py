def test_nested_model():
    from pydantic import BaseModel

    class Address(BaseModel):
        street: str
        city: str

    class Person(BaseModel):
        name: str
        address: Address

    p = Person(name="Bob", address=Address(street="123 Main", city="NYC"))
    check(p.address.city == "NYC", "city mismatch")
    print("  nested model:", p.model_dump())


def test_list_model():
    from pydantic import BaseModel

    class Item(BaseModel):
        id: int
        name: str

    class Order(BaseModel):
        items: list[Item]

    o = Order(items=[Item(id=1, name="a"), Item(id=2, name="b")])
    check(len(o.items) == 2, "item count")
    print("  list model:", len(o.items), "items")


def test_optional_fields():
    from pydantic import BaseModel

    class Config(BaseModel):
        name: str
        value: int | None = None

    c = Config(name="test")
    check(c.value is None, "default None")
    c2 = Config(name="test2", value=42)
    check(c2.value == 42, "value mismatch")
    print("  optional fields:", c.model_dump())


