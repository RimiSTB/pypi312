    eq("version", hiredis.__version__, "3.4.1")
    eq("native ext", True, ext.__file__.endswith(".so")
       or ext.__file__.endswith(".pyd"))
    eq("hiredis submodule", True, hasattr(hiredis, "hiredis"))
    for name in ("Reader", "ReplyError", "ProtocolError", "HiredisError",
                 "pack_command"):
        eq("exports %s" % name, True, hasattr(hiredis, name))


