# 8. stress: many pipelined replies round trip
# ---------------------------------------------------------------------------
def t_stress():
    section("===== stress =====")
    r = reader()
    parts = []
    for i in range(500):
        s = b"item%d" % i
        parts.append(b"$%d\r\n%s\r\n" % (len(s), s))
    blob = b"".join(parts) + b":999\r\n"
    r.feed(blob)
    ok = True
    for i in range(500):
        if r.gets() != b"item%d" % i:
            ok = False
            break
    eq("500 bulks", ok, True)
    eq("trailing int", r.gets(), 999)
    eq("exhausted", r.gets(), False)
    # a deep nested array
    inner = b":1\r\n"
    for _ in range(50):
        inner = b"*1\r\n" + inner
    eq("deep nesting", True, isinstance(single(inner), list))
    deep = single(inner)
    depth = 0
    while isinstance(deep, list):
        depth += 1
        deep = deep[0]
    eq("deep depth 50", depth, 50)
    eq("deep leaf", deep, 1)


