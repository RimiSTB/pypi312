# 3. error replies vs protocol errors
# ---------------------------------------------------------------------------
def t_errors():
    import hiredis
    section("===== errors =====")
    r = reader()
    r.feed(b"-ERR boom\r\n")
    v = r.gets()
    eq("error is ReplyError", True, isinstance(v, hiredis.ReplyError))
    eq("ReplyError is HiredisError", True,
       isinstance(v, hiredis.HiredisError))
    eq("error message", str(v), "ERR boom")
    eq("error args", v.args, ("ERR boom",))
    try:
        single(b"@garbage\r\n")
        raise AssertionError("garbage reply type did not raise")
    except hiredis.ProtocolError:
        pass


