def test_key_generation():
    from nacl.signing import SigningKey

    sk = SigningKey.generate()
    vk = sk.verify_key
    check(len(bytes(sk)) == 32, "sk size")
    check(len(bytes(vk)) == 32, "vk size")
    print("  SigningKey.generate: OK")


def test_sign_verify():
    from nacl.signing import SigningKey

    sk = SigningKey.generate()
    msg = b"message to sign"
    signed = sk.sign(msg)

    check(len(signed.signature) == 64, "sig size")
    check(signed.message == msg, "message mismatch")

    # Verify
    vk = sk.verify_key
    verified = vk.verify(signed)
    check(verified == msg, "verify mismatch")
    print("  sign + verify: OK")


def test_verify_bad_signature():
    from nacl.signing import SigningKey

    sk1 = SigningKey.generate()
    sk2 = SigningKey.generate()

    signed = sk1.sign(b"msg")
    try:
        sk2.verify_key.verify(signed)
        check(False, "should fail")
    except Exception:
        pass
    print("  verify bad signature: raises OK")


