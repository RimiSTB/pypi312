# 3. SecretBox (symmetric encryption)
# ---------------------------------------------------------------------------
def test_secretbox_encrypt_decrypt():
    from nacl.secret import SecretBox
    from nacl.utils import random

    key = random(SecretBox.KEY_SIZE)
    box = SecretBox(key)

    plaintext = b"hello pynacl secret box " * 100
    ciphertext = box.encrypt(plaintext)
    check(len(ciphertext) > len(plaintext), "ciphertext not longer")

    decrypted = box.decrypt(ciphertext)
    check(decrypted == plaintext, "decrypt mismatch")
    print("  SecretBox: encrypt %d -> %d bytes, decrypt OK" % (len(plaintext), len(ciphertext)))


def test_secretbox_wrong_key():
    from nacl.secret import SecretBox
    from nacl.utils import random

    k1 = random(SecretBox.KEY_SIZE)
    k2 = random(SecretBox.KEY_SIZE)
    box1 = SecretBox(k1)
    box2 = SecretBox(k2)

    ct = box1.encrypt(b"secret")
    try:
        box2.decrypt(ct)
        check(False, "should fail with wrong key")
    except Exception:
        pass
    print("  SecretBox wrong key: raises OK")


