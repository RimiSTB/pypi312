def test_secretbox_deterministic():
    from nacl.secret import SecretBox
    from nacl.utils import nonce as make_nonce

    key = b"\x00" * SecretBox.KEY_SIZE
    box = SecretBox(key)

    nonce1 = make_nonce(box)
    nonce2 = make_nonce(box)
    check(nonce1 != nonce2, "nonces identical")

    ct1 = box.encrypt(b"same plaintext", nonce1)
    ct2 = box.encrypt(b"same plaintext", nonce2)
    check(ct1 != ct2, "ciphertexts identical with different nonces")
    print("  SecretBox nonce uniqueness: OK")


