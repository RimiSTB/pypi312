# 5. Box (public-key encryption)
# ---------------------------------------------------------------------------
def test_box_encrypt_decrypt():
    from nacl.public import PrivateKey, Box

    sk1 = PrivateKey.generate()
    sk2 = PrivateKey.generate()

    box1 = Box(sk1, sk2.public_key)
    box2 = Box(sk2, sk1.public_key)

    plaintext = b"hello public key box " * 50
    ct = box1.encrypt(plaintext)
    pt = box2.decrypt(ct)
    check(pt == plaintext, "decrypt mismatch")
    print("  Box encrypt/decrypt: OK (%d bytes)" % len(plaintext))


def test_box_shared_key():
    from nacl.public import PrivateKey, Box

    sk1 = PrivateKey.generate()
    sk2 = PrivateKey.generate()

    box1 = Box(sk1, sk2.public_key)
    box2 = Box(sk2, sk1.public_key)

    check(box1.shared_key() == box2.shared_key(), "shared keys differ")
    print("  Box shared_key: OK")


