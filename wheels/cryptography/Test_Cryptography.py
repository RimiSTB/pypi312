def _open_libc(ffi):
    import ctypes.util
    for name in ("libc.so", "libc.so.6", "c"):
        try:
            return ffi.dlopen(name)
        except OSError:
            continue
    found = ctypes.util.find_library("c")
    if found:
        return ffi.dlopen(found)
    raise NotImplementedError("no libc available on this platform")


def cffi_libc_call():
    import cffi
    ffi = cffi.FFI()
    ffi.cdef("size_t strlen(const char *s);")
    lib = _open_libc(ffi)
    s = ffi.new("char[]", b"android-cffi")
    n = lib.strlen(s)
    assert n == 12, n


def cffi_abi_mode():
    import cffi
    ffi = cffi.FFI()
    ffi.cdef("int abs(int x);")
    lib = _open_libc(ffi)
    assert lib.abs(-5) == 5


def cffi_struct():
    import cffi
    ffi = cffi.FFI()
    ffi.cdef(
        "typedef struct { int x; int y; } point_t; "
        "point_t make_point(int x, int y);"
    )
    # use ABI mode call into a trivial function we link ourselves via ctypes-free
    # path is not available, so just validate the type machinery and FFI().new()
    p = ffi.new("point_t*")
    p.x = 3
    p.y = 4
    assert p.x == 3 and p.y == 4


def cffi_callback():
    import cffi
    ffi = cffi.FFI()
    ffi.cdef("typedef int (*cb_t)(int);")
    calls = []
    cb = ffi.callback("int(int)", lambda n: (calls.append(n), n + 1)[1])
    assert cb(10) == 11
    assert calls == [10]


