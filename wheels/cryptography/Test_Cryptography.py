def hashes():
    from cryptography.hazmat.primitives import hashes
    d = hashes.Hash(hashes.SHA256())
    d.update(b"hello cryptography")
    assert d.finalize().hex() == (
        "a301dc0ba3af7e81df0d99b6b37c4ffca866cb2ee44058bb76158db3b59d02b9"
    ), "SHA256 mismatch"


def sha512():
    from cryptography.hazmat.primitives import hashes
    d = hashes.Hash(hashes.SHA512())
    d.update(b"abc")
    h = d.finalize().hex()
    assert h.startswith("ddaf35a193617aba"), "SHA512 mismatch"


def sha3_and_blake2():
    from cryptography.hazmat.primitives import hashes
    for cls in (hashes.SHA3_256, hashes.SHA3_512):
        d = hashes.Hash(cls())
        d.update(b"data")
        assert len(d.finalize()) == d.algorithm.digest_size
    d = hashes.Hash(hashes.BLAKE2b(digest_size=64))
    d.update(b"data")
    assert len(d.finalize()) == 64
    d = hashes.Hash(hashes.SHA256())
    d.update(b"x")
    assert len(d.finalize()) == 32


def hmac_():
    from cryptography.hazmat.primitives import hashes, hmac
    h = hmac.HMAC(b"key", hashes.SHA256())
    h.update(b"message")
    assert len(h.finalize()) == 32


def cmac():
    from cryptography.hazmat.primitives import cmac
    from cryptography.hazmat.primitives.ciphers import algorithms
    c = cmac.CMAC(algorithms.AES(b"0" * 16))
    c.update(b"msg")
    assert len(c.finalize()) == 16


