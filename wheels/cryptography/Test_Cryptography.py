def rsa_sign_verify():
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import padding, rsa
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    sig = key.sign(b"data", padding.PKCS1v15(), hashes.SHA256())
    key.public_key().verify(sig, b"data", padding.PKCS1v15(), hashes.SHA256())

    pub_pem = key.public_key().public_bytes(
        serialization.Encoding.PEM,
        serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    loaded = serialization.load_pem_public_key(pub_pem)
    loaded.verify(sig, b"data", padding.PKCS1v15(), hashes.SHA256())

    priv_pem = key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )
    assert serialization.load_pem_private_key(priv_pem, None) is not None


def rsa_oaep():
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.asymmetric import padding, rsa
