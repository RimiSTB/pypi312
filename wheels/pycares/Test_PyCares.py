def _sync_query(ch, fn, timeout=DNS_SLEEP):
    """Run a callback-based channel op synchronously; return (result, errno)."""
    box = {}

    def cb(result, errno):
        box["result"] = result
        box["errno"] = errno

    fn(cb)
    ch.wait(timeout)
    if "result" not in box:
        raise AssertionError("callback did not fire within %ds" % timeout)
    return box.get("result"), box.get("errno")


