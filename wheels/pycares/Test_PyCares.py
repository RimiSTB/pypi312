def test_async_channel():
    import concurrent.futures
    ch = Channel()
    if not _can_dns():
        raise NotImplementedError("no network")
    with concurrent.futures.ThreadPoolExecutor(max_workers=1) as ex:
        fut = ex.submit(_sync_query, ch, lambda cb: ch.query(
            "example.com", pycares.QUERY_TYPE_A, callback=cb))
        result, errno = fut.result()
    check(errno is None, "async A errno %r" % (errno,))
    check(result is not None and getattr(result, "answer", None),
          "async query empty")


