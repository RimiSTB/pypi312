def diag_raw_udp(ch):
    print("  raw UDP DNS probes:")
    for srv in ch.servers:
        host, _, port = srv.partition(":")
        port = int(port or 53)
        s = None
        try:
            s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            s.settimeout(3)
            t0 = time.time()
            s.connect((host, port))
            s.send(b"\x12\x34\x01\x00\x00\x01\x00\x00\x00\x00\x00\x00"
                   b"\x07example\x03com\x00\x00\x01\x00\x01")
            data = s.recv(512)
            print("    %s:%d -> %d bytes in %.1fms"
                  % (host, port, len(data), (time.time() - t0) * 1000))
        except Exception as e:
            print("    %s:%d -> FAIL (%s)" % (host, port, e))
        finally:
            try:
                if s is not None:
                    s.close()
            except Exception:
                pass


