"""
On-device verification for the cross-compiled brotli 1.2.0 wheel.

Run after installing:
    pip install brotli-1.2.0-cp312-cp312-android_24_<ABI>.whl

Usage:
    python Test_Brotli.py [--quick]

Exit code 0 = everything required PASSed.

NOTE: the wheel ships the native accelerator as _brotli.cpython-312.so and a
thin pure-python wrapper brotli.py. brotli.compress()/decompress() MUST hit
the compiled backend, not a pure-python fallback (there is no fallback - if
the .so is missing, `import brotli` fails entirely).

Generated by RIMI
"""
import sys
import os
import traceback

RESULTS = []


def test(name, fn):
    try:
        fn()
        RESULTS.append((name, "PASS", None))
    except NotImplementedError as exc:
        RESULTS.append((name, "SKIP", str(exc)))
    except Exception as exc:
        RESULTS.append((name, "FAIL", "%s: %s" % (type(exc).__name__, exc)))
        traceback.print_exc()


def section(title):
    print("=" * 60)
    print(title)
    print("=" * 60)


# ---------------------------------------------------------------------------
# 1. import surface + version
# ---------------------------------------------------------------------------
def imports_correct():
    import brotli
    assert brotli.__version__ == "1.2.0", brotli.__version__
    assert hasattr(brotli, "compress")
    assert hasattr(brotli, "decompress")
    assert hasattr(brotli, "Compressor")
    assert hasattr(brotli, "Decompressor")
    assert hasattr(brotli, "error")
    assert brotli.MODE_GENERIC == 0
    assert brotli.MODE_TEXT == 1
    assert brotli.MODE_FONT == 2


def native_backend_loaded():
    # The C accelerator must exist as a real .so next to brotli.py.
    import brotli
    import importlib.util
    pkg_dir = os.path.dirname(brotli.__file__)
    found = False
    for name in os.listdir(pkg_dir):
        if name.startswith("_brotli") and name.endswith((".so", ".pyd")):
            found = True
    assert found, "no _brotli native extension in %s" % pkg_dir
    spec = importlib.util.find_spec("_brotli")
    assert spec is not None and spec.origin and spec.origin.endswith((".so", ".pyd")), \
        "_brotli did not resolve to a compiled extension"


