def bad_input_raises():
    import brotli
    try:
        brotli.decompress(b"this is not valid brotli data at all!!!")
    except brotli.error:
        return
    raise AssertionError("corrupt stream did not raise brotli.error")


def type_errors():
    import brotli
    for bad in (None, "str", 123, 1.5, [1, 2, 3]):
        try:
            brotli.compress(bad)
        except (TypeError, ValueError):
            pass
        else:
            raise AssertionError("compress(%r) did not raise" % (bad,))


def main():
    quick = "--quick" in sys.argv
    section("1. import surface")
    test("imports brotli 1.2.0", imports_correct)
    test("native _brotli backend loaded", native_backend_loaded)

    section("2. roundtrip correctness")
    test("simple roundtrip", simple_roundtrip)
    test("known vector deterministic", known_vector)
    test("binary roundtrip", binary_roundtrip)
    test("all qualities 0-11", quality_range)
    test("empty + tiny inputs", empty_and_tiny)
    test("all modes roundtrip", modes_roundtrip)
    test("streaming Compressor", streaming_compressor)
    test("streaming Decompressor", streaming_decompressor)

    section("3. error handling")
    test("corrupt stream raises brotli.error", bad_input_raises)
    test("bad types raise TypeError", type_errors)

    print()
    print("=" * 60)
    print("SUMMARY")
    print("=" * 60)
    fails = 0
    skips = 0
    for name, status, why in RESULTS:
        mark = "  OK" if status == "PASS" else (" SKIP" if status == "SKIP" else "FAIL")
        print("%s %s" % (mark, name))
        if why:
            print("        -> %s" % why)
        if status == "FAIL":
            fails += 1
        elif status == "SKIP":
            skips += 1
    print()
    passed = len(RESULTS) - fails - skips
    print("passed=%d skipped=%d failed=%d" % (passed, skips, fails))
    if fails:
        print("RESULT: FAILED")
    elif skips and not quick:
        print("RESULT: PASSED (with informational skips)")
    else:
        print("RESULT: PASSED")
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
