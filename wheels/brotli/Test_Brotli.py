# 2. roundtrip correctness (known values)
# ---------------------------------------------------------------------------
def simple_roundtrip():
    import brotli
    data = b"hello brotli 12345" * 1000
    c = brotli.compress(data)
    assert isinstance(c, bytes)
    assert len(c) < len(data), "compressed should be smaller for repetitive data"
    assert brotli.decompress(c) == data


def known_vector():
    # deterministic: same input + same params -> identical output on every ABI
    import brotli
    data = b"PySTB" * 64
    c = brotli.compress(data, quality=11, mode=brotli.MODE_TEXT)
    assert brotli.decompress(c) == data
    # vector is stable across builds/ABIs
    assert c == brotli.compress(data, quality=11, mode=brotli.MODE_TEXT), \
        "brotli output not deterministic"


def binary_roundtrip():
    import brotli
    import os
    rnd = bytes((i * 31 + 7) & 0xFF for i in range(4096))
    c = brotli.compress(rnd, quality=5)
    assert brotli.decompress(c) == rnd


def quality_range():
    import brotli
    data = b"quality test payload" * 200
    for q in range(0, 12):
        c = brotli.compress(data, quality=q)
        assert brotli.decompress(c) == data, "quality %d roundtrip failed" % q


def empty_and_tiny():
    import brotli
    assert brotli.decompress(brotli.compress(b"")) == b""
    assert brotli.decompress(brotli.compress(b"a")) == b"a"
    assert brotli.decompress(brotli.compress(b"ab" * 2)) == b"abab"


def modes_roundtrip():
    import brotli
    data = b"<html><body>font test data \xef\xbb\xbf</body></html>" * 50
    for mode in (brotli.MODE_GENERIC, brotli.MODE_TEXT, brotli.MODE_FONT):
        c = brotli.compress(data, mode=mode)
        assert brotli.decompress(c) == data, "mode %d roundtrip failed" % mode


def streaming_compressor():
    import brotli
    comp = brotli.Compressor(quality=9)
    chunks = []
    for i in range(100):
        chunks.append(comp.process(b"stream block %d " % i))
    tail = comp.finish()
    data = b"".join(chunks) + tail
    assert brotli.decompress(data) == b"".join(b"stream block %d " % i for i in range(100))


def streaming_decompressor():
    import brotli
    src = b"The quick brown fox jumps over the lazy dog. " * 300
    c = brotli.compress(src)
    dec = brotli.Decompressor()
    out = bytearray()
    step = 7
    for i in range(0, len(c), step):
        out += dec.process(c[i:i + step])
    assert bytes(out) == src
    assert dec.is_finished()


