# 8. utilization
# ---------------------------------------------------------------------------
def test_disk_usage_tmpdir():
    import psutil
    import tempfile
    tmp = tempfile.gettempdir()
    u = psutil.disk_usage(tmp)
    check(u.total > 0, "total=%d" % u.total)
    print("  disk_usage %s: %dMB" % (tmp, u.total // (1024 * 1024)))


