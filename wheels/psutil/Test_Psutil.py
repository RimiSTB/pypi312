import os
import sys

RESULTS = []


def test(name, fn):
    try:
        fn()
        RESULTS.append(("PASS", name))
    except NotImplementedError:
        RESULTS.append(("SKIP", name))
    except Exception as e:
        RESULTS.append(("FAIL", name, str(e)))


def section(title):
    print("\n===== %s =====" % title)


def check(cond, msg):
    if not cond:
        raise AssertionError(msg)


# ---------------------------------------------------------------------------
# 1. import + version
# ---------------------------------------------------------------------------
def test_import():
    import psutil
    check(hasattr(psutil, "__version__"), "no __version__")
    print("  version:", psutil.__version__)


def test_c_extensions():
    import psutil._psutil_linux as _linux
    import psutil._psutil_posix as _posix
    check(hasattr(_linux, "linux_platform_info"), "no linux_platform_info")
    check(hasattr(_posix, "net_if_addrs"), "no net_if_addrs")


# ---------------------------------------------------------------------------
# 2. CPU
# ---------------------------------------------------------------------------
def test_cpu_count():
    import psutil
    n = psutil.cpu_count(logical=True)
    check(n is not None and n > 0, "cpu_count=%r" % n)
    print("  cpu_count:", n)


def test_cpu_times():
    import psutil
    t = psutil.cpu_times()
    check(hasattr(t, "user"), "no user field")
    check(hasattr(t, "system"), "no system field")
    print("  cpu_times user=%.1f system=%.1f" % (t.user, t.system))


def test_cpu_percent():
    import psutil
    p = psutil.cpu_percent(interval=0.1)
    check(0.0 <= p <= 100.0, "cpu_percent=%r" % p)
    print("  cpu_percent:", p)


# ---------------------------------------------------------------------------
# 3. memory
# ---------------------------------------------------------------------------
def test_virtual_memory():
    import psutil
    m = psutil.virtual_memory()
    check(m.total > 0, "total=%d" % m.total)
    check(0 <= m.percent <= 100, "percent=%r" % m.percent)
    print("  virtual_memory: total=%dMB percent=%.1f%%" % (m.total // (1024 * 1024), m.percent))


def test_swap_memory():
    import psutil
    s = psutil.swap_memory()
    check(hasattr(s, "total"), "no total")
    print("  swap_memory: total=%dMB" % (s.total // (1024 * 1024)))


# ---------------------------------------------------------------------------
# 4. disk
# ---------------------------------------------------------------------------
def test_disk_usage():
    import psutil
    u = psutil.disk_usage("/")
    check(u.total > 0, "total=%d" % u.total)
    check(0 <= u.percent <= 100, "percent=%r" % u.percent)
    print("  disk_usage /: total=%dMB percent=%.1f%%" % (u.total // (1024 * 1024), u.percent))


def test_disk_partitions():
    import psutil
    parts = psutil.disk_partitions(all=False)
    check(isinstance(parts, list), "not list")
    print("  disk_partitions: %d entries" % len(parts))


def test_disk_io():
    import psutil
    io = psutil.disk_io_counters()
    check(io is not None, "None returned")
    check(hasattr(io, "read_bytes"), "no read_bytes")
    print("  disk_io_counters: read=%dMB write=%dMB" % (io.read_bytes // (1024 * 1024), io.write_bytes // (1024 * 1024)))


# ---------------------------------------------------------------------------
# 5. network
# ---------------------------------------------------------------------------
def test_net_io():
    import psutil
    n = psutil.net_io_counters()
    check(hasattr(n, "bytes_sent"), "no bytes_sent")
    check(hasattr(n, "bytes_recv"), "no bytes_recv")
    print("  net_io_counters: sent=%dKB recv=%dKB" % (n.bytes_sent // 1024, n.bytes_recv // 1024))


def test_net_if_addrs():
    import psutil
    addrs = psutil.net_if_addrs()
    check(isinstance(addrs, dict), "not dict")
    check(len(addrs) > 0, "empty")
    print("  net_if_addrs: %d interfaces" % len(addrs))


def test_net_if_stats():
    import psutil
    stats = psutil.net_if_stats()
    check(isinstance(stats, dict), "not dict")
    check(len(stats) > 0, "empty")
    first = list(stats.values())[0]
    check(hasattr(first, "isup"), "no isup")
    print("  net_if_stats: %d interfaces" % len(stats))


