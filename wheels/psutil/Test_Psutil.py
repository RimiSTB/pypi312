# 6. processes
# ---------------------------------------------------------------------------
def test_pids():
    import psutil
    pids = psutil.pids()
    check(len(pids) > 0, "empty")
    check(isinstance(pids[0], int), "not int")
    print("  pids: %d processes" % len(pids))


def test_process_info():
    import psutil
    pid = os.getpid()
    p = psutil.Process(pid)
    check(p.pid == pid, "pid mismatch")
    check(p.name(), "no name")
    check(p.status(), "no status")
    check(p.create_time() > 0, "create_time=%r" % p.create_time())
    print("  process %d: name=%s status=%s" % (pid, p.name(), p.status()))


def test_process_memory():
    import psutil
    p = psutil.Process(os.getpid())
    m = p.memory_info()
    check(m.rss > 0, "rss=%d" % m.rss)
    check(m.vms > 0, "vms=%d" % m.vms)
    print("  process memory: rss=%dMB vms=%dMB" % (m.rss // (1024 * 1024), m.vms // (1024 * 1024)))


def test_process_cmdline():
    import psutil
    p = psutil.Process(os.getpid())
    cmd = p.cmdline()
    check(len(cmd) > 0, "empty cmdline")
    print("  cmdline: %s" % " ".join(cmd[:3]))


