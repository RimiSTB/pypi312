def overflow():
    import numpy as np
    # uint8 arithmetic wraps around
    assert (np.array([200], np.uint8) + np.array([100], np.uint8))[0] == 44
    # int division floors, true division gives float
    assert np.array([5]) // 2 == np.array([2])
    assert np.array([5]) / 2 == np.array([2.5])


