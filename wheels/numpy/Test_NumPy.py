def masking():
    import numpy as np
    a = np.arange(12).reshape(3, 4)
    assert (a[a > 5] > 5).all()
    assert len(a[(a > 2) & (a < 8)]) == 5
    assert (a[a % 2 == 0] % 2 == 0).all()
    m = a.copy()
    m[m < 5] = 0
    assert m.min() == 0
    m[:, 0] = -1
    assert (m[:, 0] == -1).all()


