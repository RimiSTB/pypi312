def t_escape():
    section("===== escape() =====")
    from markupsafe import escape
    eq("angle brackets", str(escape("a <b>c</b> d")), "a &lt;b&gt;c&lt;/b&gt; d")
    eq("ampersand first", str(escape("A & B")), "A &amp; B")
    eq("quotes", str(escape("say 'hi' \"yo\"")), "say &#39;hi&#39; &#34;yo&#34;")
    eq("greater sign", str(escape("5 > 3 < 4")), "5 &gt; 3 &lt; 4")
    eq("clean string unchanged", str(escape("plain text")), "plain text")
    eq("int", str(escape(42)), "42")
    eq("none", str(escape(None)), "None")
    eq("float", str(escape(1.5)), "1.5")
    eq("returns Markup", type(escape("x")).__name__, "Markup")
    eq("unicode kept", str(escape("caf\u00e9 \u2603")), "caf\u00e9 \u2603")
    eq("emoji kept", str(escape("\U0001f600")), "\U0001f600")


