# 3. Markup class: concat/format/join/mul
# ---------------------------------------------------------------------------
def t_markup():
    section("===== Markup =====")
    from markupsafe import Markup, escape
    m = Markup("<b>hi</b>")
    eq("str subclass", isinstance(m, str), True)
    eq("html marker", m.__html__() is m, True)

    # string concat auto-escapes the str side
    res = m + " & friends"
    eq("concat escapes str", str(res), "<b>hi</b> &amp; friends")
    eq("concat returns Markup", type(res).__name__, "Markup")

    # Markup + Markup does NOT double-escape
    eq("markup+markup no double escape", str(Markup("<i>a</i>") + Markup("<i>b</i>")),
       "<i>a</i><i>b</i>")

    # format auto-escapes substitutions
    f = Markup("Hello, {0}! {x}").format(escape("<world>"), x="<x>")
    eq("format escapes", str(f), "Hello, &lt;world&gt;! &lt;x&gt;")

    # % style
    p = Markup("%s and %s") % ("<a>", "<b>")
    eq("percent escapes", str(p), "&lt;a&gt; and &lt;b&gt;")

    # join
    joined = Markup(", ").join(["<a>", "<b>"])
    eq("join escapes", str(joined), "&lt;a&gt;, &lt;b&gt;")

    # mul
    eq("mul", str(Markup("ab") * 2), "abab")

    # striptags
    eq("striptags", Markup("<b>Keep</b><script>x</script>").striptags(), "Keepx")

    # unescape round trip
    e = escape("<b>hi & bye</b>")
    eq("unescape round trip", str(Markup(str(e)).unescape()), "<b>hi & bye</b>")

    # __html__ protocol: escape() calls it
    class Obj:
        def __html__(self):
            return "<em>already html</em>"

    eq("escape uses __html__", str(escape(Obj())), "<em>already html</em>")


