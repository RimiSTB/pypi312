    def test_save_load_model():
        import numpy as np
        import xgboost as xgb
        import tempfile
        import os
        np.random.seed(42)
        X = np.random.rand(100, 10).astype(np.float32)
        y = (X[:, 0] * 2).astype(np.float32)
        dtrain = xgb.DMatrix(X, label=y)
        params = {'max_depth': 3, 'eta': 0.1, 'objective': 'reg:squarederror', 'verbosity': 0}
        model = xgb.train(params, dtrain, num_boost_round=20)

        # Save as JSON
        json_path = os.path.join(tempfile.gettempdir(), "test_model.json")
        model.save_model(json_path)
        model2 = xgb.Booster()
        model2.load_model(json_path)

        # Compare predictions
        dtest = xgb.DMatrix(X)
        p1 = model.predict(dtest)
        p2 = model2.predict(dtest)
        assert np.allclose(p1, p2)
        os.remove(json_path)
        return "JSON save/load roundtrip OK"

    test("save/load model (JSON)", test_save_load_model)

