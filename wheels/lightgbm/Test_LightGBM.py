def save_load_model():
    import os
    import tempfile
    import numpy as np
    import lightgbm as lgb
    rng = np.random.default_rng(42)
    X = rng.random((100, 5))
    y = rng.integers(0, 2, size=100)
    ds = lgb.Dataset(X, label=y)
    params = {"objective": "binary", "metric": "binary_logloss", "verbose": -1, "num_threads": 1}
    bst = lgb.train(params, ds, num_boost_round=3)

    d = tempfile.mkdtemp()
    p = os.path.join(d, "model.txt")
    bst.save_model(p)
    assert os.path.exists(p)
    assert os.path.getsize(p) > 0

    bst2 = lgb.Booster(model_file=p)
    pred1 = bst.predict(X[:3])
    pred2 = bst2.predict(X[:3])
    assert all(abs(a - b) < 1e-6 for a, b in zip(pred1, pred2))


