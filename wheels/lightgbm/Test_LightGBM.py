def train_binary():
    import numpy as np
    import lightgbm as lgb
    rng = np.random.default_rng(42)
    X = rng.random((200, 5))
    y = (X[:, 0] + X[:, 1] > 1.0).astype(int)
    ds = lgb.Dataset(X, label=y)
    params = {
        "objective": "binary",
        "metric": "binary_logloss",
        "verbose": -1,
        "num_threads": 1,
    }
    bst = lgb.train(params, ds, num_boost_round=5)
    assert bst is not None
    pred = bst.predict(X[:5])
    assert pred.shape == (5,)
    assert all(0.0 <= p <= 1.0 for p in pred)


def train_regression():
    import numpy as np
    import lightgbm as lgb
    rng = np.random.default_rng(42)
    X = rng.random((200, 5))
    y = X[:, 0] * 2 + X[:, 2] * 3 + rng.normal(0, 0.1, 200)
    ds = lgb.Dataset(X, label=y)
    params = {
        "objective": "regression",
        "metric": "rmse",
        "verbose": -1,
        "num_threads": 1,
    }
    bst = lgb.train(params, ds, num_boost_round=10)
    pred = bst.predict(X[:5])
    assert pred.shape == (5,)
    assert all(abs(v) < 100 for v in pred)


