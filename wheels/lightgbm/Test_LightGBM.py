def early_stopping():
    import numpy as np
    import lightgbm as lgb
    rng = np.random.default_rng(42)
    X = rng.random((200, 5))
    y = rng.integers(0, 2, size=200)
    ds = lgb.Dataset(X, label=y)
    params = {"objective": "binary", "verbose": -1, "num_threads": 1}
    evals = lgb.Dataset(X[:50], label=y[:50])
    bst = lgb.train(
        params, ds, num_boost_round=100,
        valid_sets=[evals],
        callbacks=[lgb.early_stopping(3), lgb.log_evaluation(-1)],
    )
    assert bst.num_trees() < 100


