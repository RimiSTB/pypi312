def ft2font_basic():
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib.ft2font import FT2Font
    import matplotlib.font_manager as fm
    # Find a default font
    default = fm.findfont(fm.FontProperties())
    assert os.path.exists(default)
    font = FT2Font(default)
    assert font.num_faces >= 1
    assert font.family_name is not None


