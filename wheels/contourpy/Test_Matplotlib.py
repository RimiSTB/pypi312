def contour_plot():
    import numpy as np
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots()
    x = np.linspace(-2, 2, 50)
    y = np.linspace(-2, 2, 50)
    xx, yy = np.meshgrid(x, y)
    zz = np.sin(xx) * np.cos(yy)
    cs = ax.contour(xx, yy, zz)
    assert cs is not None
    plt.close(fig)


