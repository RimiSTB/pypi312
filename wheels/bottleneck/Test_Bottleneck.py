# 7. stress: large arrays + dtype coverage
# ---------------------------------------------------------------------------
def t_stress():
    import bottleneck as bn
    import numpy as np
    section("===== stress =====")
    rng = np.random.default_rng(42)
    data = rng.random(500000)
    data[::97] = np.nan
    near("big nansum", bn.nansum(data), np.nansum(data))
    near("big nanmean", bn.nanmean(data), np.nanmean(data))
    near("big nanmax", bn.nanmax(data), np.nanmax(data))
    near("big nanstd", bn.nanstd(data), np.nanstd(data))
    eq("big move_mean shape", bn.move_mean(data, window=1000,
                                          min_count=1).shape, data.shape)
    m = bn.move_mean(data, window=1000, min_count=1)
    eq("big move_mean finite", True, np.isfinite(m[100000]))
    # integer dtype support
    i = np.arange(1000, dtype=np.int64) * 2
    eq("int nansum", bn.nansum(i), i.sum())
    eq("int median", bn.median(i), np.median(i))
    # 2D axis support
    d2 = rng.random((200, 300))
    eq("2d nanmean axis0 shape", bn.nanmean(d2, axis=0).shape, (300,))
    near("2d nanmean axis0", bn.nanmean(d2, axis=0)[0], np.nanmean(d2, axis=0)[0])
    near("2d nanmean axis1", bn.nanmean(d2, axis=1)[5], np.nanmean(d2, axis=1)[5])


