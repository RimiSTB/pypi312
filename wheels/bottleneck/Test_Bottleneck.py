def eq(label, a, b):
    if a != b:
        raise AssertionError("%s: %r != %r" % (label, a, b))
    return True


def near(label, a, b, rtol=1e-7, atol=1e-9):
    import numpy as np
    if not np.isclose(a, b, rtol=rtol, atol=atol):
        raise AssertionError("%s: %r != %r" % (label, a, b))
    return True


